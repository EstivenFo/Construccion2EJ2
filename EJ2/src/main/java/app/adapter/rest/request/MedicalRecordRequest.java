package app.adapter.rest.request;

public class MedicalRecordRequest {

    private String creationDate;         // Se envía como texto en formato ISO: "2025-11-06"
    private String patientId;            // Documento o ID del paciente
    private String doctorId;             // Documento o ID del médico
    private String consultationReason;   // Motivo de la consulta
    private String symptoms;             // Síntomas reportados
    private String diagnosis;            // Diagnóstico médico
    private String treatment;            // Tratamiento indicado

    public String getCreationDate() {
        return creationDate;
    }

    public void setCreationDate(String creationDate) {
        this.creationDate = creationDate;
    }

    public String getPatientId() {
        return patientId;
    }

    public void setPatientId(String patientId) {
        this.patientId = patientId;
    }

    public String getDoctorId() {
        return doctorId;
    }

    public void setDoctorId(String doctorId) {
        this.doctorId = doctorId;
    }

    public String getConsultationReason() {
        return consultationReason;
    }

    public void setConsultationReason(String consultationReason) {
        this.consultationReason = consultationReason;
    }

    public String getSymptoms() {
        return symptoms;
    }

    public void setSymptoms(String symptoms) {
        this.symptoms = symptoms;
    }

    public String getDiagnosis() {
        return diagnosis;
    }

    public void setDiagnosis(String diagnosis) {
        this.diagnosis = diagnosis;
    }

    public String getTreatment() {
        return treatment;
    }

    public void setTreatment(String treatment) {
        this.treatment = treatment;
    }
}
